/// Reads the web app's dictionaries (apps/web/src/i18n/{en,uz,ru}.ts), the single source of
/// every user-facing string. Used by tool/gen_messages.dart, which writes
/// lib/i18n/messages.g.dart, and by test/i18n_test.dart, which fails when the two drift.
///
/// The files are TypeScript object literals of one shape: `"key": "value",` or
/// `"key": { one: "...", other: "..." },`, with `//` and `/* */` comments. Anything else
/// is a FormatException, so a new construct in the web files cannot slip through quietly.
library;

import 'dart:io';

/// A message: a String, or a plural as `{category: text}` (CLDR categories).
typedef Message = Object;

const languages = ['en', 'uz', 'ru'];

/// language -> key -> message, in file order.
Map<String, Map<String, Message>> readWebMessages(String i18nDir) => {
      for (final lang in languages)
        lang: parseMessages(File('$i18nDir/$lang.ts').readAsStringSync(), lang),
    };

Map<String, Message> parseMessages(String source, String lang) {
  final tokens = _tokenize(source);
  // The object after `export const <lang>` ... `= {`.
  var i = 0;
  while (i < tokens.length - 2 &&
      !(tokens[i].text == 'const' && tokens[i + 1].text == lang)) {
    i++;
  }
  while (i < tokens.length && tokens[i].text != '=') {
    i++;
  }
  i++;
  _expect(tokens, i, '{');
  i++;
  final out = <String, Message>{};
  while (tokens[i].text != '}') {
    final key = _string(tokens, i);
    _expect(tokens, i + 1, ':');
    i += 2;
    if (tokens[i].text == '{') {
      i++;
      final plural = <String, String>{};
      while (tokens[i].text != '}') {
        final category = tokens[i].text;
        if (tokens[i].isString || !_categories.contains(category)) {
          throw FormatException('$lang.ts: "$key": bad plural category "$category"');
        }
        _expect(tokens, i + 1, ':');
        plural[category] = _string(tokens, i + 2);
        i += 3;
        if (tokens[i].text == ',') i++;
      }
      if (!plural.containsKey('other')) {
        throw FormatException('$lang.ts: "$key": a plural needs "other"');
      }
      out[key] = plural;
      i++;
    } else {
      out[key] = _string(tokens, i);
      i++;
    }
    if (out.length != out.keys.toSet().length) throw FormatException('duplicate "$key"');
    if (tokens[i].text == ',') i++;
  }
  return out;
}

const _categories = {'zero', 'one', 'two', 'few', 'many', 'other'};

class _Token {
  const _Token(this.text, {this.isString = false});
  final String text;
  final bool isString;
}

String _string(List<_Token> tokens, int i) {
  if (!tokens[i].isString) {
    throw FormatException('expected a string, got "${tokens[i].text}"');
  }
  return tokens[i].text;
}

void _expect(List<_Token> tokens, int i, String text) {
  if (i >= tokens.length || tokens[i].text != text || tokens[i].isString) {
    throw FormatException('expected "$text", got "${i < tokens.length ? tokens[i].text : 'EOF'}"');
  }
}

List<_Token> _tokenize(String s) {
  final out = <_Token>[];
  var i = 0;
  while (i < s.length) {
    final c = s[i];
    if (c.trim().isEmpty) {
      i++;
    } else if (s.startsWith('//', i)) {
      final end = s.indexOf('\n', i);
      i = end < 0 ? s.length : end;
    } else if (s.startsWith('/*', i)) {
      final end = s.indexOf('*/', i + 2);
      if (end < 0) throw const FormatException('unclosed comment');
      i = end + 2;
    } else if (c == '"' || c == "'") {
      final b = StringBuffer();
      i++;
      while (s[i] != c) {
        if (s[i] == '\n') throw const FormatException('newline inside a string');
        if (s[i] == r'\') {
          i++;
          b.write(switch (s[i]) { 'n' => '\n', 't' => '\t', _ => s[i] });
        } else {
          b.write(s[i]);
        }
        i++;
      }
      out.add(_Token(b.toString(), isString: true));
      i++;
    } else if (RegExp(r'[A-Za-z_$]').hasMatch(c)) {
      final m = RegExp(r'[A-Za-z0-9_$]+').matchAsPrefix(s, i)!;
      out.add(_Token(m.group(0)!));
      i = m.end;
    } else {
      out.add(_Token(c));
      i++;
    }
  }
  return out;
}

/// The Dart source of lib/i18n/messages.g.dart for these messages.
String generateDart(Map<String, Map<String, Message>> messages) {
  String lit(String v) =>
      "'${v.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'";
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_messages.dart from apps/web/src/i18n/{en,uz,ru}.ts.')
    ..writeln('// Do not edit: change the web dictionaries, then run')
    ..writeln('//   dart run tool/gen_messages.dart')
    ..writeln('// test/i18n_test.dart fails when this file and the web files differ.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('const Map<String, Map<String, Object>> webMessages = {');
  for (final lang in messages.keys) {
    b.writeln("  '$lang': {");
    for (final e in messages[lang]!.entries) {
      final v = e.value;
      if (v is String) {
        b.writeln('    ${lit(e.key)}: ${lit(v)},');
      } else {
        final forms = (v as Map<String, String>).entries.map((f) => "'${f.key}': ${lit(f.value)}");
        b.writeln('    ${lit(e.key)}: <String, String>{${forms.join(', ')}},');
      }
    }
    b.writeln('  },');
  }
  b.writeln('};');
  return b.toString();
}
